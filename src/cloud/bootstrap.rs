//! Everything a fresh cloud server needs to become a tvpn server: freshly
//! generated keys, the server/client configs, and the first-boot script
//! (cloud-init user data) that installs tvpn and runs `tvpn server up`.

use crate::config::{Config, Endpoint, Interface, Peer};
use crate::keys::Key;
use crate::server::ServerMeta;
use std::net::{IpAddr, SocketAddr};

pub const LISTEN_PORT: u16 = 51820;
const SERVER_ADDRESS: &str = "10.77.0.1/24";
const CLIENT_ADDRESS: &str = "10.77.0.2/32";

/// Keys and configs for one on-demand server. Generated locally for every
/// session and never reused, so nothing outlives the server.
pub struct Plan {
    pub server: Config,
    pub meta: ServerMeta,
    client_key: Key,
    psk: Key,
}

pub struct Options<'a> {
    /// tvpn version to install on the server (normally the client's own).
    pub version: &'a str,
    /// GitHub `owner/repo` that hosts install.sh and the release binaries.
    pub repo: &'a str,
    /// Hard upper bound on the server's lifetime.
    pub max_minutes: u32,
    /// Terminate after this many minutes without a connected client.
    pub idle_minutes: u32,
}

impl Plan {
    pub fn generate() -> Plan {
        let server_key = Key::generate_private();
        let client_key = Key::generate_private();
        let psk = Key::generate_preshared();
        let server = Config {
            interface: Interface {
                private_key: server_key,
                addresses: vec![SERVER_ADDRESS.parse().expect("valid")],
                listen_port: Some(LISTEN_PORT),
                dns: Vec::new(),
                dns_search: Vec::new(),
                mtu: None,
            },
            peers: vec![Peer {
                name: Some("tvpn client".into()),
                public_key: client_key.public_key(),
                preshared_key: Some(psk),
                allowed_ips: vec![CLIENT_ADDRESS.parse().expect("valid")],
                endpoint: None,
                persistent_keepalive: None,
            }],
        };
        let meta = ServerMeta {
            endpoint: format!("tvpn-cloud:{LISTEN_PORT}"),
            dns: Vec::new(),
            client_allowed_ips: vec!["0.0.0.0/0".parse().expect("valid"), "::/0".parse().expect("valid")],
            keepalive: 25,
        };
        Plan { server, meta, client_key, psk }
    }

    /// Full-tunnel client config pointing at the server's public IP.
    pub fn client_config(&self, server_ip: IpAddr, label: &str) -> Config {
        let endpoint = SocketAddr::new(server_ip, LISTEN_PORT);
        Config {
            interface: Interface {
                private_key: self.client_key,
                addresses: vec![CLIENT_ADDRESS.parse().expect("valid")],
                listen_port: None,
                dns: vec!["1.1.1.1".parse().expect("valid"), "1.0.0.1".parse().expect("valid")],
                dns_search: Vec::new(),
                mtu: None,
            },
            peers: vec![Peer {
                name: Some(label.to_string()),
                public_key: self.server.interface.private_key.public_key(),
                preshared_key: Some(self.psk),
                allowed_ips: vec!["0.0.0.0/0".parse().expect("valid"), "::/0".parse().expect("valid")],
                endpoint: Some(Endpoint { host: endpoint.ip().to_string(), port: endpoint.port() }),
                persistent_keepalive: Some(25),
            }],
        }
    }

    /// The first-boot script for the server.
    pub fn user_data(&self, o: &Options<'_>) -> String {
        let mut server_conf = self.server.to_wg_string();
        if !server_conf.ends_with('\n') {
            server_conf.push('\n');
        }
        let server_json = serde_json::to_string_pretty(&self.meta).expect("serializable");
        USER_DATA
            .replace("@SERVER_CONF@", &server_conf)
            .replace("@SERVER_JSON@", &server_json)
            .replace("@VERSION@", o.version)
            .replace("@REPO@", o.repo)
            .replace("@MAX_MINUTES@", &o.max_minutes.to_string())
            .replace("@IDLE_MINUTES@", &o.idle_minutes.to_string())
    }
}

const USER_DATA: &str = r#"#!/bin/bash
# tvpn cloud server bootstrap, generated by tvpn @VERSION@. Runs once on first boot.
set -euo pipefail
exec >>/var/log/tvpn-bootstrap.log 2>&1
echo "tvpn bootstrap starting: $(date -u)"

# Safety net 1: never outlive the maximum lifetime. Shutting down terminates
# the instance (it is launched with InstanceInitiatedShutdownBehavior=terminate).
shutdown -h +@MAX_MINUTES@ "tvpn: maximum server lifetime reached" || true

install -d -m 700 /root/.config/tvpn/server
cat > /root/.config/tvpn/server/server.conf <<'TVPN_EOF'
@SERVER_CONF@TVPN_EOF
cat > /root/.config/tvpn/server/server.json <<'TVPN_EOF'
@SERVER_JSON@
TVPN_EOF
chmod 600 /root/.config/tvpn/server/server.conf /root/.config/tvpn/server/server.json

# Install tvpn (install.sh verifies checksums): the client's version if it is
# released, otherwise the latest release. The server side only needs
# `tvpn server up` and `tvpn status --json`, which every release has.
install_tvpn() {
  curl -fsSL "https://raw.githubusercontent.com/@REPO@/main/install.sh" \
    | TVPN_VERSION="$1" TVPN_INSTALL_DIR=/usr/local/bin sh
}
for attempt in 1 2 3 4 5 6; do
  if install_tvpn "@VERSION@" || install_tvpn latest; then
    break
  fi
  echo "install attempt $attempt failed; retrying"
  sleep 5
done
/usr/local/bin/tvpn --version

cat > /etc/systemd/system/tvpn-server.service <<'TVPN_EOF'
[Unit]
Description=tvpn cloud server
After=network-online.target
Wants=network-online.target

[Service]
Environment=HOME=/root TVPN_NO_SUDO=1 NO_COLOR=1
ExecStart=/usr/local/bin/tvpn server up --quiet
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
TVPN_EOF

# Safety net 2: power off (= terminate) once no client has been connected for
# @IDLE_MINUTES@ minutes, so a forgotten server doesn't keep costing money.
cat > /usr/local/bin/tvpn-idle-watchdog <<'TVPN_EOF'
#!/bin/bash
sleep 600
idle=0
while true; do
  if HOME=/root /usr/local/bin/tvpn status --json 2>/dev/null | grep -Eq '"last_handshake_secs": [0-9]+'; then
    idle=0
  else
    idle=$((idle + 1))
  fi
  if [ "$idle" -ge @IDLE_MINUTES@ ]; then
    shutdown -h now "tvpn: no client connected for @IDLE_MINUTES@ minutes"
  fi
  sleep 60
done
TVPN_EOF
chmod 755 /usr/local/bin/tvpn-idle-watchdog

cat > /etc/systemd/system/tvpn-idle-watchdog.service <<'TVPN_EOF'
[Unit]
Description=Terminate this tvpn cloud server when nobody uses it
After=tvpn-server.service

[Service]
ExecStart=/usr/local/bin/tvpn-idle-watchdog

[Install]
WantedBy=multi-user.target
TVPN_EOF

systemctl daemon-reload
systemctl enable --now tvpn-server.service tvpn-idle-watchdog.service
echo "tvpn bootstrap done: $(date -u)"
"#;

#[cfg(test)]
mod tests {
    use super::*;

    fn options() -> Options<'static> {
        Options { version: "9.8.7", repo: "someone/T-VPN", max_minutes: 480, idle_minutes: 15 }
    }

    #[test]
    fn configs_match_each_other() {
        let plan = Plan::generate();
        plan.server.validate_server().unwrap();
        let client = plan.client_config("203.0.113.9".parse().unwrap(), "tvpn cloud (Mumbai)");
        client.validate_client().unwrap();
        assert_eq!(client.peers[0].public_key, plan.server.interface.private_key.public_key());
        assert_eq!(plan.server.peers[0].public_key, client.interface.private_key.public_key());
        assert_eq!(client.peers[0].preshared_key, plan.server.peers[0].preshared_key);
        assert_eq!(client.peers[0].endpoint.as_ref().unwrap().to_string(), "203.0.113.9:51820");
        // Fresh keys every time.
        assert_ne!(Plan::generate().server.interface.private_key, plan.server.interface.private_key);
    }

    #[test]
    fn user_data_embeds_working_configs() {
        let plan = Plan::generate();
        let script = plan.user_data(&options());
        assert!(!script.contains('@'), "unreplaced placeholder in:\n{script}");
        assert!(script.contains("https://raw.githubusercontent.com/someone/T-VPN/main/install.sh"));
        assert!(script.contains("install_tvpn \"9.8.7\" || install_tvpn latest"));
        assert!(script.contains("shutdown -h +480"));
        assert!(script.contains("[ \"$idle\" -ge 15 ]"));

        // The embedded server.conf round-trips to the same config.
        let start = script.find("server.conf <<'TVPN_EOF'\n").unwrap() + "server.conf <<'TVPN_EOF'\n".len();
        let end = start + script[start..].find("TVPN_EOF").unwrap();
        let parsed = Config::parse(&script[start..end]).unwrap().config;
        assert_eq!(parsed, plan.server);

        // And server.json parses as server metadata.
        let start = script.find("server.json <<'TVPN_EOF'\n").unwrap() + "server.json <<'TVPN_EOF'\n".len();
        let end = start + script[start..].find("\nTVPN_EOF").unwrap();
        let meta: ServerMeta = serde_json::from_str(&script[start..end]).unwrap();
        assert_eq!(meta, plan.meta);
    }

    #[test]
    #[cfg(unix)]
    fn user_data_is_valid_bash() {
        let script = Plan::generate().user_data(&options());
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("user-data.sh");
        std::fs::write(&path, script).unwrap();
        let out = std::process::Command::new("bash").arg("-n").arg(&path).output().unwrap();
        assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    }
}
