//! Linux specifics: DNS (systemd-resolved or /etc/resolv.conf), forwarding, iptables.

use super::{Applied, DnsRecord, FirewallRule, ServerPlan, SysctlRecord, run};
use crate::paths;
use crate::privilege::which;
use anyhow::{Context, Result, bail};
use std::fs;
use std::net::IpAddr;
use std::path::{Path, PathBuf};

const RESOLV_CONF: &str = "/etc/resolv.conf";
const RESOLV_HEADER: &str = "# Generated by tvpn while connected; the original is restored on disconnect.";

fn uses_systemd_resolved() -> bool {
    if which("resolvectl").is_none() {
        return false;
    }
    let link_to_resolved =
        fs::read_link(RESOLV_CONF).map(|t| t.to_string_lossy().contains("systemd/resolve")).unwrap_or(false);
    let stub = fs::read_to_string(RESOLV_CONF)
        .map(|c| c.lines().any(|l| l.trim() == "nameserver 127.0.0.53"))
        .unwrap_or(false);
    link_to_resolved || stub
}

pub fn apply_dns(iface: &str, dns: &[IpAddr], search: &[String], full_tunnel: bool) -> Result<DnsRecord> {
    if uses_systemd_resolved() {
        let servers: Vec<String> = dns.iter().map(ToString::to_string).collect();
        let mut args = vec!["dns", iface];
        args.extend(servers.iter().map(String::as_str));
        run("resolvectl", &args)?;
        let mut domains: Vec<&str> = search.iter().map(String::as_str).collect();
        if full_tunnel {
            // Route every DNS lookup through this link.
            domains.push("~.");
        }
        if !domains.is_empty() {
            let mut args = vec!["domain", iface];
            args.extend(domains);
            run("resolvectl", &args)?;
        }
        if full_tunnel {
            let _ = run("resolvectl", &["default-route", iface, "true"]);
        }
        return Ok(DnsRecord::Resolved { interface: iface.to_string() });
    }

    // Plain /etc/resolv.conf: back it up and replace it.
    let path = Path::new(RESOLV_CONF);
    let runtime = paths::runtime_dir();
    fs::create_dir_all(&runtime).with_context(|| format!("cannot create {}", runtime.display()))?;
    let backup = runtime.join("resolv.conf.backup");
    let symlink_target = match fs::symlink_metadata(path) {
        Ok(m) if m.file_type().is_symlink() => Some(fs::read_link(path)?),
        _ => None,
    };
    let original = fs::read(path).unwrap_or_default();
    fs::write(&backup, &original).with_context(|| format!("cannot write {}", backup.display()))?;

    let mut contents = String::from(RESOLV_HEADER);
    contents.push('\n');
    for ip in dns.iter().take(3) {
        contents.push_str(&format!("nameserver {ip}\n"));
    }
    if !search.is_empty() {
        contents.push_str(&format!("search {}\n", search.join(" ")));
    }
    if symlink_target.is_some() {
        // Never write through the symlink: the target may be shared (e.g. WSL).
        fs::remove_file(path).context("cannot replace /etc/resolv.conf")?;
    }
    if let Err(e) = fs::write(path, contents) {
        if let Some(target) = &symlink_target {
            let _ = std::os::unix::fs::symlink(target, path);
        }
        bail!("cannot write /etc/resolv.conf: {e}");
    }
    Ok(DnsRecord::ResolvConf { backup, symlink_target })
}

pub fn revert_dns(rec: &DnsRecord, warnings: &mut Vec<String>) {
    match rec {
        DnsRecord::Resolved { interface } => {
            // The link usually disappears with the tunnel; that also clears its DNS.
            let _ = run("resolvectl", &["revert", interface]);
        }
        DnsRecord::ResolvConf { backup, symlink_target } => {
            restore_resolv_conf(backup, symlink_target.as_deref(), warnings);
        }
        _ => {}
    }
}

fn restore_resolv_conf(backup: &PathBuf, symlink_target: Option<&Path>, warnings: &mut Vec<String>) {
    let path = Path::new(RESOLV_CONF);
    let current = fs::read_to_string(path).unwrap_or_default();
    if !current.starts_with(RESOLV_HEADER) {
        warnings.push("/etc/resolv.conf was changed by another program while connected; left as is".into());
        let _ = fs::remove_file(backup);
        return;
    }
    let result = match symlink_target {
        Some(target) => fs::remove_file(path).and_then(|_| std::os::unix::fs::symlink(target, path)),
        None => fs::read(backup).and_then(|orig| fs::write(path, orig)),
    };
    match result {
        Ok(()) => {
            let _ = fs::remove_file(backup);
        }
        Err(e) => warnings
            .push(format!("could not restore /etc/resolv.conf ({e}); a backup is at {}", backup.display())),
    }
}

fn set_sysctl(path: &str, value: &str, applied: &mut Applied) -> Result<()> {
    let previous =
        fs::read_to_string(path).with_context(|| format!("cannot read {path}"))?.trim().to_string();
    if previous == value {
        return Ok(());
    }
    fs::write(path, value).with_context(|| format!("cannot write {path}"))?;
    applied.sysctls.push(SysctlRecord { path: PathBuf::from(path), previous });
    Ok(())
}

fn add_rule(rule: FirewallRule, insert: bool, applied: &mut Applied) -> Result<()> {
    let mut args: Vec<&str> = vec!["-t", &rule.table, if insert { "-I" } else { "-A" }, &rule.chain];
    args.extend(rule.spec.iter().map(String::as_str));
    run(&rule.program, &args)?;
    applied.firewall.push(rule);
    Ok(())
}

fn rule(program: &str, table: &str, chain: &str, spec: &[&str]) -> FirewallRule {
    FirewallRule {
        program: program.into(),
        table: table.into(),
        chain: chain.into(),
        spec: spec.iter().map(|s| s.to_string()).collect(),
    }
}

pub fn apply_server(
    plan: &ServerPlan<'_>,
    applied: &mut Applied,
    persist: &mut dyn FnMut(&Applied),
    notes: &mut Vec<String>,
) -> Result<()> {
    let has_v4 = plan.subnets.iter().any(|n| n.addr().is_ipv4());
    let has_v6 = plan.subnets.iter().any(|n| n.addr().is_ipv6());

    if plan.nat {
        if has_v4 {
            set_sysctl("/proc/sys/net/ipv4/ip_forward", "1", applied)?;
            persist(applied);
        }
        if has_v6 {
            if let Err(e) = set_sysctl("/proc/sys/net/ipv6/conf/all/forwarding", "1", applied) {
                notes.push(format!("IPv6 forwarding not enabled: {e:#}"));
            }
            persist(applied);
        }
    }

    if !plan.firewall && !plan.nat {
        return Ok(());
    }

    let wan = plan.wan.clone().or_else(super::default_route_interface);
    if plan.nat && wan.is_none() {
        notes.push("could not detect the internet-facing interface; pass --wan <iface> to enable NAT".into());
    }
    let port = plan.listen_port.to_string();

    for (program, is_v6) in [("iptables", false), ("ip6tables", true)] {
        if (is_v6 && !has_v6) || (!is_v6 && !has_v4) {
            continue;
        }
        if which(program).is_none() {
            notes.push(format!(
                "`{program}` not found: firewall/NAT rules were not added. Install iptables (or set up masquerading yourself)."
            ));
            continue;
        }
        let mut wanted = Vec::new();
        if plan.firewall {
            wanted.push((
                rule(program, "filter", "INPUT", &["-p", "udp", "--dport", &port, "-j", "ACCEPT"]),
                true,
            ));
            wanted.push((rule(program, "filter", "FORWARD", &["-i", plan.interface, "-j", "ACCEPT"]), true));
            wanted.push((rule(program, "filter", "FORWARD", &["-o", plan.interface, "-j", "ACCEPT"]), true));
        }
        if plan.nat
            && let Some(wan) = &wan
        {
            for net in plan.subnets.iter().filter(|n| n.addr().is_ipv6() == is_v6) {
                let src = net.trunc().to_string();
                wanted.push((
                    rule(program, "nat", "POSTROUTING", &["-s", &src, "-o", wan, "-j", "MASQUERADE"]),
                    false,
                ));
            }
        }
        for (r, insert) in wanted {
            if let Err(e) = add_rule(r, insert, applied) {
                notes.push(format!("{e:#}"));
            }
            persist(applied);
        }
    }
    Ok(())
}
